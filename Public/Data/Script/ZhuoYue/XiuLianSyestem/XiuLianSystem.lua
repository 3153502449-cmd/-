			if UpLevelNeedMoney == nil then
				UpLevelNeedMoney = 0
			end
			return UpLevelNeedMoney
		end
		return 0
	end
	if DataType == "UpLevelNeedExp" then
		local nBookLevel = GetXiuLianMiJiInfo(sceneId,selfId,nIndex,"Level")
