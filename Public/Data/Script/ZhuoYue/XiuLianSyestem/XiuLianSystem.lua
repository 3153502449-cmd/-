			for i = 1,5 do
				local tempJingJie = GetXiuLianMiJiInfo(sceneId,selfId,i,"JingJie")
				if tempJingJie > nMaxJingJie then
					nMaxJingJie = tempJingJie
				end
			end
			return nMaxJingJie
		end
		if nIndex == 2 then
			local nMaxJingJie = 0
			for i = 6,11 do
				local tempJingJie = GetXiuLianMiJiInfo(sceneId,selfId,i,"JingJie")
				if tempJingJie > nMaxJingJie then
					nMaxJingJie = tempJingJie
				end
			end
			return nMaxJingJie
		end
		if nIndex == 3 then
			local nMaxJingJie = 0
			for i = 12,15 do
				local tempJingJie = GetXiuLianMiJiInfo(sceneId,selfId,i,"JingJie")
				if tempJingJie > nMaxJingJie then
					nMaxJingJie = tempJingJie
				end
			end
			return nMaxJingJie
		end
		return 1
	end
end

