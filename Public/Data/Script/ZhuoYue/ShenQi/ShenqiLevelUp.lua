--**********************************
-- 神器升级
--**********************************
function x500506_OnShenqiLevelUp(sceneId,selfId,nItemPos)

	if nItemPos == nil  or nItemPos == -1 then
		return
	end
	local nItemID = GetItemTableIndexByIndex(sceneId, selfId, nItemPos )
	--	判断是否是神器
	if nItemID < 10310001 or nItemID > 10311039 then
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_08}")
		return
	end
	-- 判断神器是否是92级
	local nEquipLevel = GetBagItemLevel(sceneId, selfId, nItemPos)
	if nEquipLevel == 92 then
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_09}")
		return
	end
	-- 判断旧神器是否在神器升级表里
	local bRet, nDesLevel,nShenqiLevel, nCostMoney, nCostItemID, nCostItemNum ,nShenqiItemID,Visid = GetShenqiLevelUpInfo(nItemID)
	if 0 == bRet or nil == bRet then
		x500506_NotifyFailTips( sceneId, selfId,"神器升级数据错误，无此升级信息")
		return
	end

	-- 判断对应的神符是否够
	local nHaveNum = LuaFnGetAvailableItemCount(sceneId, selfId,nCostItemID)
	if nHaveNum < nCostItemNum then
		x500506_NotifyFailTips( sceneId, selfId,GetItemName(sceneId,nCostItemID).."数量不足，无法升级。")
		return
	end
	-- 判断钱是否够用
	local nMoneyJZ = GetMoneyJZ(sceneId,selfId)
	local nMoneyJB = GetMoney(sceneId,selfId)
	local nHaveMoney = nMoneyJZ + nMoneyJB
	if nCostMoney > nHaveMoney then
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_21}")
		return
	end
	LuaFnDelAvailableItem(sceneId,selfId,nCostItemID,nCostItemNum) --材料扣除
	--开始升级流程
	AddMoney(sceneId, selfId,-nCostMoney)
	LuaFnEquipTransToNew(sceneId,selfId,nItemPos,nShenqiItemID)
	local xjjjjjjjjjj = 6
	if nShenqiLevel >= 42 and nShenqiLevel <92 then
		xjjjjjjjjjj = 6
	elseif nShenqiLevel==92 then
	    xjjjjjjjjjj = 7
	elseif nShenqiLevel == 102 then
	    xjjjjjjjjjj = 8
		if nShenqiItemID >=10313001 and nShenqiItemID < 10313040 then
			xjjjjjjjjjj = 9
		end
	end
	if LuaFnGetItmQual(sceneId,selfId,nItemPos) ~=xjjjjjjjjjj then
		LuaFnSetItemQual(sceneId,selfId,nItemPos, xjjjjjjjjjj)
	end
	LuaFnRewashEquipAttr(sceneId,selfId,nItemPos)
    if Visid ~= 0 then
	LuaFnSetEquipVisual(sceneId,selfId,nItemPos,Visid)
	end
	if nItemPos ~= nil and nItemPos > -1 then
		LuaFnSendSpecificImpactToUnit(sceneId, selfId, selfId, selfId, 49, 0);
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_23}")
		local strText = format("#P#{_INFOUSR%s}双手奉上#G%s#P个#Y%s#P后，只见苏州(248,142)#R欧冶子#P轻描淡写间便将#G%s#P级#cff0000[(神)%s]#P升级为#G%s#P级#cff0000[(神)%s]#P，匠者如斯，实为天人矣！",
						GetName(sceneId,selfId),
						nCostItemNum,
						GetItemName(sceneId,nCostItemID),
						nDesLevel,
						GetItemName(sceneId,nItemID),
						nShenqiLevel,
						GetItemName(sceneId,nShenqiItemID)
						)
		BroadMsgByChatPipe(sceneId, selfId, strText, 4)
	else
		x500506_NotifyFailTips( sceneId, selfId,"神器升级失败！")
		return
	end
end
--**********************************
-- 材料数量请求
--**********************************
function x500506_GetMaterialNum(sceneId,selfId,nItemID)
	if nItemID ~= nil and tonumber(nItemID) > 30000000 then
		local nMaterialNum = LuaFnGetAvailableItemCount(sceneId, selfId,nItemID)
		BeginUICommand(sceneId)
	        UICommand_AddInt( sceneId,nMaterialNum)
	        EndUICommand( sceneId )
	    DispatchUICommand( sceneId, selfId,  2019060301)
		return
	end
end
