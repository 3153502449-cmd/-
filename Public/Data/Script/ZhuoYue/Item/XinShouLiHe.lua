	if GetLevel(sceneId,selfId) < 15 then
		x892326_Tip(sceneId,selfId,"请在15级以后再来使用礼包");
		return 0 
	end
	if GetMenPai(sceneId,selfId) == 9 then
		x892326_Tip(sceneId,selfId,"请在加入门派以后再来使用礼包");
		return 0 
	end
	--背包空间检测
	if LuaFnGetPropertyBagSpace(sceneId,selfId) < 18 then
		x892326_Tip(sceneId,selfId,"背包空间不足！");
		return 0 
	end
	local Itemid = LuaFnGetItemIndexOfUsedItem(sceneId,selfId);
	local nBagPos = LuaFnGetBagIndexOfUsedItem(sceneId,selfId);
	local nMenPai = GetMenPai(sceneId,selfId);
	local nSuperWeaponId = 0;
	
	for i = 1,20 do
		local pos = TryRecieveItem( sceneId, selfId, x892326_g_Item[i], 1)
		if LuaFnGetItemBindStatus(sceneId,selfId,pos) ~= 1 then
			LuaFnItemBind(sceneId,selfId,pos)
		end
	end

	LuaFnSendSpecificImpactToUnit(sceneId, selfId, selfId, selfId, 151, 0)
	--x892326_Tip(sceneId,selfId,format("恭喜你成功打开了%s！获得%s一把",GetItemName(sceneId,x892326_g_GiftItem),GetItemName(sceneId,nSuperWeaponId)))
	x892326_Xinshouxiangqian( sceneId, selfId )
	return 1
end

