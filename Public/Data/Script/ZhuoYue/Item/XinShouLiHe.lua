--**********************************
--条件检测入口：
--系统会在技能检测的时间点调用这个接口，并根据这个函数的返回值确定以后的流程是否执行。
--返回1：条件检测通过，可以继续执行；返回0：条件检测失败，中断后续执行。
--**********************************
function x892326_OnConditionCheck( sceneId, selfId )
	--校验使用的物品
	if(1~=LuaFnVerifyUsedItem(sceneId, selfId)) then
		return 0
	end
	--等级检查
	if GetLevel(sceneId,selfId) < 15 then
		x892326_Tip(sceneId,selfId,"请在15级以后再来使用礼包");
		return 0 
	end
	if GetMenPai(sceneId,selfId) == 9 then
		x892326_Tip(sceneId,selfId,"请在加入门派以后再来使用礼包");
		return 0 
	end
	local itemTblIndex = LuaFnGetItemIndexOfUsedItem( sceneId, selfId );
	if x892326_g_GiftItem ~= itemTblIndex then
		x892326_Tip(sceneId,selfId,"物品非法");
		return 0 
	end
	--背包空间检测
	if LuaFnGetPropertyBagSpace(sceneId,selfId) < 1 then
		x892326_Tip(sceneId,selfId,"#{XSHLY_150522_166}");
		return 0 
	end
	return 1; --不需要任何条件，并且始终返回1。
end

