function x900007_OnDressWash(sceneId,selfId,nPos)
	if nPos == nil or nPos < 0 then
		return
	end
	local nItemId = GetItemTableIndexByIndex(sceneId, selfId, nPos)
	local _,nEquipData = LuaFnGetItemCreator( sceneId, selfId,nPos)
	local nFinalData = ""
	if nEquipData ~= nil then
		local nPos1,nPos2,nColorId = strfind(nEquipData,"&CO(%w%w%w%w)")
		if nPos1 ~= nil and nPos2 ~= nil then
			nFinalData = gsub(nEquipData,"&CO(%w%w%w%w)","")
		else
			x900007_NotifyTip( sceneId, selfId, "#{SZPR_091023_27}" )
			return
		end
	else
		x900007_NotifyTip( sceneId, selfId, "#{SZPR_091023_27}" )
		return
	end
	local nMoneySelf = GetMoneyJZ(sceneId,selfId) + GetMoney(sceneId,selfId)
	if nMoneySelf < x900007_DressPraint then
        x900007_NotifyTip( sceneId, selfId,  "#{RXZS_090804_11}" )
        return
	end
	local nDefaultVisual = x900007_DressColor[nItemId][1][1]
	LuaFnCostMoneyWithPriority( sceneId, selfId, x900007_DressPraint)
	LuaFnSetEquipItemCreatorEx( sceneId, selfId,nPos,nFinalData)
	LuaFnSetEquipVisual(sceneId,selfId,nPos,nDefaultVisual)	
	x900007_NotifyTip( sceneId, selfId,  "#{SZPR_091023_86}" )
end
