function x900007_ConvertDecoWeapon( sceneId, selfId,pos,pos1,nIdeaidx)
	if nIdeaidx <0 or nIdeaidx >60 then 
	 return
	end
	nIdeaidx=nIdeaidx+1

	
	if LuaFnGetPropertyBagSpace( sceneId, selfId ) <1 or  LuaFnGetMaterialBagSpace( sceneId, selfId ) < 1 then 	
	x900007_NotifyTip( sceneId, selfId,"请保证道具材料栏都有1格空位")	
	return
	end
	local nWPId = GetItemTableIndexByIndex(sceneId, selfId, pos1)
	if nWPId ~= 30505909 then 
		x900007_NotifyTip( sceneId, selfId,"你缺少缀梦灵石")	
	  return
	end


	local nItemId = GetItemTableIndexByIndex(sceneId, selfId, pos)
	if nItemId <1 then
		return
	end	
	if 	nItemId <10311001 or  nItemId >10315049 then 
		x900007_NotifyTip( sceneId, selfId,  "只有102神器才能进行幻饰" )
	return
	end

	local MpID = GetMenPai( sceneId, selfId )
	if x900007_Wuqiyuan[MpID] == nil then 
		x900007_NotifyTip( sceneId, selfId, "只有102神器才能进行幻饰" )
		return
	end
	
	local reply = LuaFnCostMoneyWithPriority(sceneId,selfId,500000)
	if reply == -1 then
		x900007_NotifyTip( sceneId, selfId, "金钱不足" )
		return
	end

	local sunT = LuaFnGetAvailableItemCount(sceneId, selfId, 30505909)
	if sunT  <20 then 
			x900007_NotifyTip( sceneId, selfId,"你的缀梦灵石不足20个")	
		return
	end
		
	if LuaFnDelAvailableItem(sceneId,selfId,30505909,20) ~=1 then 
			x900007_NotifyTip( sceneId, selfId,"删除物品失败")
			return
	end
	
    local nNewid = x900007_Wuqiyuan[MpID][nIdeaidx]
	local Visual = List_Strsdwing[MpID][nIdeaidx]
	if nNewid == nil then 
		x900007_NotifyTip( sceneId, selfId,"策划错误")
	   return
	end
	
		LuaFnEquipTransToNew(sceneId, selfId, pos, nNewid )
		LuaFnSetEquipVisual(sceneId, selfId, pos, Visual )
        x900007_NotifyTip( sceneId, selfId,"恭喜，神器幻饰成功!!!")
		LuaFnSendSpecificImpactToUnit(sceneId, selfId, selfId, selfId, 152, 0)
end


