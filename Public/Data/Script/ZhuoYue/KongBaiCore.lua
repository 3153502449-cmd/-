function x890096_xunzhaocy( sceneId, selfId, key, keyy )
    if key == nil or key > 5 then
       return
    end
    if GetItemCount(sceneId, selfId, x890096_g_Yinpiao)>=1  then
		BeginEvent( sceneId )
			AddText( sceneId, "  你身上有银票，正在跑商！我不能帮助你。" )
		EndEvent( sceneId )
		DispatchEventList( sceneId, selfId )
		return
    end
    if GetTeamId(sceneId,selfId)>=0 and 
		IsTeamFollow(sceneId, selfId)==1 and
		LuaFnIsTeamLeader(sceneId,selfId)==1 then
		num=LuaFnGetFollowedMembersCount( sceneId, selfId)
		local mems = {}
		for	i=0,num-1 do
			mems[i] = GetFollowedMember(sceneId, selfId, i)
			if mems[i] == -1 then
				return
			end
			if IsHaveMission(sceneId,mems[i],4021) > 0 then
				x890096_NotifyTip( sceneId, selfId,  "  你队伍成员中有人有漕运货舱在身，我们驿站不能为你提供传送服务。" )
				return
			end
		end
	end

	--漕运相关
	if IsHaveMission(sceneId,selfId,4021) > 0 then
		x890096_NotifyTip( sceneId, selfId,  "  你有漕运货舱在身，我们驿站不能为你提供传送服务。" )
		return
	end
	
	--检测Impact状态驻留效果
	for i, ImpactId in x890096_g_Impact_NotTransportList do
		if LuaFnHaveImpactOfSpecificDataIndex(sceneId, selfId, ImpactId) ~= 0 then
			x890096_NotifyTip( sceneId, selfId,  x890096_g_Impact_NotTransportList[i] )			
			return 0
		end
	end
	
local cssceneId = 0
local csx = 0
local csy = 0
local csdj = 0
	
	if key == 1 then
		cssceneId = x890096_g_mpInfo[keyy][1]
		csx = x890096_g_mpInfo[keyy][2]
		csy = x890096_g_mpInfo[keyy][3]
		csdj = x890096_g_mpInfo[keyy][4]
	elseif key == 2 then
		cssceneId = x890096_g_mpInfo1[keyy][1]
		csx = x890096_g_mpInfo1[keyy][2]
		csy = x890096_g_mpInfo1[keyy][3]
		csdj = x890096_g_mpInfo1[keyy][4]
	elseif key == 4 then
		cssceneId = x890096_g_mpInfo2[keyy][1]
		csx = x890096_g_mpInfo2[keyy][2]
		csy = x890096_g_mpInfo2[keyy][3]
		csdj = x890096_g_mpInfo2[keyy][4]
	elseif key == 3 then
		cssceneId = x890096_g_mpInfo3[keyy][1]
		csx = x890096_g_mpInfo3[keyy][2]
		csy = x890096_g_mpInfo3[keyy][3]
		csdj = x890096_g_mpInfo3[keyy][4]
	elseif key == 5 then
		cssceneId = x890096_g_mpInfo4[keyy][1]
		csx = x890096_g_mpInfo4[keyy][2]
		csy = x890096_g_mpInfo4[keyy][3]
		csdj = x890096_g_mpInfo4[keyy][4]
	end
	if (cssceneId == nil) then
		return
	end
	if (csx == 0) then
		return
	end
	if (csy == 0) then
		return
	end	
	

	CallScriptFunction( (400900), "TransferFunc", sceneId, selfId, cssceneId, csx, csy, csdj );
end

