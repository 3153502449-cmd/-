--**********************************
function x889383_OnPetPossHuanSe(sceneId,selfId,nSelect,nCheck)
	if nSelect == nil or nCheck == nil then
		return
	end
	if nCheck ~= 0 and nCheck ~= 1 then
		return
	end
	if x889383_g_FutiVisual[nSelect] == nil then
		return
	end
	if GetLevel(sceneId,selfId) < 45 then
		x889383_Tips(sceneId,selfId,"#{FTHS_120719_24}")
		return
	end
	--检查是不是珍兽附体中
	if CallScriptFunction(900009,"IsInPossession",sceneId,selfId) == 1 then
		x889383_Tips( sceneId, selfId, "#{FTHS_120719_26}")
		return
	end
	local nVisualID = floor(nSelect/1000)
	local nPossVisualData = x889383_GetPossVisualData(sceneId,selfId)
	if nPossVisualData ~= nil then
		--首先检查该附体有无激活
		if nPossVisualData[1][nVisualID] == 0 then
			local nMaterialID = x889383_g_Huanse_PetPossList[nVisualID]
			--首先检查背包有没有
			if LuaFnGetAvailableItemCount(sceneId, selfId,nMaterialID) < 1 then
				-- LuaFnBuyNotEnoughMaterial(sceneId,selfId,nMaterialID,1,nCheck) 这里屏蔽自动购买，将附体部分作为掉落
				x889383_Tips(sceneId,selfId,x889383_g_Huanse_PetPossNameList[nVisualID].."效果未激活，无法进行幻色。")
				return
			else
				x889383_Tips(sceneId,selfId,"#{FTWX_110511_19}")
				return
			end
		end
		--附体激活后
		if LuaFnGetAvailableItemCount(sceneId, selfId,x889383_g_Huanse_HuanHunDan) < 1 then
			-- LuaFnBuyNotEnoughMaterial(sceneId,selfId,x889383_g_Huanse_HuanHunDan,1,nCheck)
			x889383_Tips(sceneId,selfId,"#{FTHS_120719_27}")
			return
		end
		if GetMoneyJZ(sceneId,selfId) + GetMoney(sceneId,selfId) < x889383_g_Huanse_NeedMoney then
			x889383_Tips( sceneId, selfId, "#{FTHS_120719_28}" )
			return
		end
		--开始幻色
		local nRandom = random(2,4)
		local nRandom_B = random(1,1000)
		--稀有颜色
		if nRandom_B > 990 then
			nRandom = random(7,9)
		elseif nRandom_B > 700 then
			nRandom = random(5,6)
		end
		LuaFnDelAvailableItem(sceneId,selfId,x889383_g_Huanse_HuanHunDan,1) --材料扣除
		LuaFnCostMoneyWithPriority( sceneId, selfId,x889383_g_Huanse_NeedMoney) --扣钱
		if nPossVisualData[nVisualID][nRandom] == 1 then
			x889383_Tips( sceneId, selfId, "本次幻色所得您已拥有，请继续进行幻色" )
		end
		nPossVisualData[nVisualID][nRandom] = 1
		x889383_SetPossVisualData(sceneId,selfId,nPossVisualData)
		x889383_Tips( sceneId, selfId, "#{FTHS_120719_29}" )
		
		x889383_OnUpdate(sceneId,selfId)
--		BeginUICommand( sceneId )
--			UICommand_AddInt( sceneId,(nVisualID * 1000 + nRandom))
--		EndUICommand( sceneId )
