function x002108_WriteMysticData(sceneId,objID,ItemID,ItemName,ItemPrize,ItemNum)
	local FinData = ""
	for i =1,6 do --暂时就先6个商品
        FinData = FinData..tostring(ItemID[i]).."\t"..tostring(ItemName[i]).."\t"..tostring(ItemPrize[i]).."\t"..tostring(ItemNum[i]).."\n"
    end
	local Coldfile = openfile("./Shop_MysticData.txt", "w")
	if Coldfile and nil ~= Coldfile then
		if FinData == nil or FinData == "" then
			return
		end
		write(Coldfile, FinData)
		closefile(Coldfile)
	else
		return
	end
	return
end
function x002108_ReadMysticData(sceneId,selfId)
	local nHand = openfile("./Shop_MysticData.txt", "r")
	local Data = {}
	local ItemID,ItemName,ItemPrize,ItemNum = {},{},{},{}
	if nHand and nil ~= nHand then
		for i=1, 6 do 
			local nLineData = read(nHand, "*l")
			if nLineData == nil then
				break
			end
			Data[i] = nLineData
		end
		closefile(nHand)
		for i = 1,6 do
		    local x,y,ItemIDa,ItemNamea,ItemPrizea,ItemNuma = strfind(Data[i],"(.*)\t(.*)\t(.*)\t(.*)")	
			if x ~= nil and y ~= nil then
			    ItemID[i] = tonumber(ItemIDa)
				ItemName[i] = ItemNamea
				ItemPrize[i] = tonumber(ItemPrizea)
				ItemNum[i] = tonumber(ItemNuma)
			else
				x002108_MsgTip(sceneId,selfId,"神秘商人数据异常，目前正在维护中，请稍后......")
		        return
			end
		end
	else
		x002108_RefreshMysticItem(sceneId, selfId)
	end
	return ItemID,ItemName,ItemPrize,ItemNum
end

