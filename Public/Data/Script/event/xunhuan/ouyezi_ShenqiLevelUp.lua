--**********************************
-- 神器升级
--**********************************
function x500506_OnShenqiLevelUp(sceneId,selfId,nItemPos,nSelectLevel,IsQurrel)
	--IsQurrel 1已经二次确认
	IsQurrel = 1 --默认二次确认过了
	if nItemPos == nil or nSelectLevel == nil or IsQurrel == nil or nItemPos == -1 then
		return
	end
	local nItemID = GetItemTableIndexByIndex(sceneId, selfId, nItemPos )
	--	判断是否是神器
	if nItemID < x500506_g_EQUIP_SHENQI_BEGIN or nItemID > x500506_g_EQUIP_SHENQI_END then
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_08}")
		return
	end
	-- 判断神器是否小于92级
	local nEquipLevel = GetBagItemLevel(sceneId, selfId, nItemPos)
	if nEquipLevel >= 92 then
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_09}")
		return
	end
	-- 判断旧神器是否在神器升级表里
	local bRet, nShenqiLevel, nCostMoney, nCostItemID, nCostItemNum ,nShenqiItemID = GetShenqiLevelUpInfo(nItemID, nSelectLevel)
	if 0 == bRet or nil == bRet then
		x500506_NotifyFailTips( sceneId, selfId,"神器升级数据错误，无此升级信息")
		return
	end
	-- 神器等级配置错误
	if nEquipLevel ~= nShenqiLevel then
		x500506_NotifyFailTips( sceneId, selfId,"神器升级数据错误，神器等级不一致")
		return
	end
	
	-- 现有神器等级大于等于目标神器等级，策划配表错误
	if nShenqiLevel >= nSelectLevel then
		x500506_NotifyFailTips( sceneId, selfId,"神器升级数据错误，目标等级小于源等级")
		return
	end
	-- 判断对应的神符是否够
	local nHaveNum = LuaFnGetAvailableItemCount(sceneId, selfId,nCostItemID)
	if nHaveNum < nCostItemNum then
		x500506_NotifyFailTips( sceneId, selfId,GetItemName(sceneId,nCostItemID).."数量不足，无法升级。")
		return
	end
	-- 判断钱是否够用
	local nMoneyJZ = GetMoneyJZ(sceneId,selfId)
	local nMoneyJB = GetMoney(sceneId,selfId)
	local nHaveMoney = nMoneyJZ + nMoneyJB
	if nCostMoney > nHaveMoney then
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_21}")
		return
	end
	LuaFnDelAvailableItem(sceneId,selfId,nCostItemID,nCostItemNum) --材料扣除
	--开始升级流程
	local nNewPos = LuaFnEquipTransToNew(sceneId,selfId,nItemPos,nShenqiItemID)
	if nNewPos ~= nil and nNewPos > -1 then
		LuaFnSendSpecificImpactToUnit(sceneId, selfId, selfId, selfId, 49, 0);
		x500506_NotifyFailTips( sceneId, selfId,"#{XSQSJ_160812_23}")
		local strText = format("#P#{_INFOUSR%s}双手奉上#G%s#P个#Y%s#P后，只见苏州大宗师#{_INFOAIM355,234,1,欧冶子}#R欧冶子#P轻描淡写间便将%s级#cff0000[(神)%s]#P升级为%s级%s，匠者如斯，实为天人矣！",
						GetName(sceneId,selfId),
						nCostItemNum,
						GetItemName(sceneId,nCostItemID),
						nEquipLevel,
						GetItemName(sceneId,nItemID),
						nSelectLevel,
						GetItemName(sceneId,nShenqiItemID)
						)
		BroadMsgByChatPipe(sceneId, selfId, strText, 4)
	else
		x500506_NotifyFailTips( sceneId, selfId,"神器升级失败！")
		return
	end
end
