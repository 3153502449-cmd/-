--**********************************
--装备升级
--**********************************
function x502024_OnLiuboEquipLevelup(sceneId,selfId,nPos)
	if nPos == nil then
		x502024_NotifyTips( sceneId, selfId, "#{SLDZ_100805_96}" )
		return
	end
	local nEquipID = GetItemTableIndexByIndex(sceneId, selfId, nPos)
	local isLiuboEquip, needMoney, materialNum1,nEquipNext,nEquipNextLevel = x502024_LuaFnGetLiuboEquipInfo(nEquipID)
	if isLiuboEquip ~= nil and isLiuboEquip == 1 and needMoney ~= nil then
		if LuaFnIsItemLocked(sceneId, selfId, nPos) ~= 0 then
			x502024_NotifyTips( sceneId, selfId,"#{DPMCS_180827_4}") --物品已加锁
			return
		end
		local equipevel = mod(floor(nEquipID/100),10)
		if(equipevel < 9) then
			--看看钱够不够
			local nMoneyJZ = GetMoneyJZ(sceneId,selfId)
			local nMoneyJB = GetMoney(sceneId,selfId)
			local nMoneySelf = nMoneyJZ + nMoneyJB
			if nMoneySelf < needMoney then
				x502024_NotifyTips( sceneId, selfId,"#{SLDZ_100805_100}" )
				return
			end
			--看看龙魂玉够不够
			local nLHYnUM = LuaFnGetAvailableItemCount(sceneId, selfId,x502024_LHY_ItemID)
			if nLHYnUM < materialNum1 then
				x502024_NotifyTips( sceneId, selfId, "升级需要"..materialNum1.."#H个龙魂玉，数量不足。" )
				return
			end
			--扣钱扣道具升级啦！
			if LuaFnDelAvailableItem(sceneId,selfId,x502024_LHY_ItemID,materialNum1) ~= 1 then --材料扣除
			   return
			end
			LuaFnCostMoneyWithPriority( sceneId, selfId,needMoney) --扣钱
			--上电视
			LuaFnEquipTransToNew(sceneId,selfId,nPos,nEquipNext)
			LuaFnRewashEquipAttr(sceneId,selfId,nPos)
			x502024_NotifyTips( sceneId, selfId,"你的"..GetItemName(sceneId,nEquipID).."升级成功！" )
			local nNewItemID = GetItemTableIndexByIndex(sceneId, selfId, nPos)
			local nMsg = format("#{_INFOUSR%s}#H口中念念有词：“马跳日，象飞田；炮打隔山子，车走一条线；将帅不出九宫外，小卒过河不回头……”，话音未落，突然发现从宋辽战场得来的%s#H升级到了%s#H级！",
						GetName(sceneId,selfId),
						GetItemName(sceneId,nNewItemID),
						nEquipNextLevel)
			BroadMsgByChatPipe(sceneId, selfId, nMsg, 4)
			return
		else
			x502024_NotifyTips( sceneId, selfId,"#{SLDZ_100805_99}")
			return
		end
	else
		x502024_NotifyTips( sceneId, selfId,"#{SLDZ_100805_97}")
		return
	end
end
--**********************************
--装备升星
--**********************************
function x502024_OnLiuboEquipStarup(sceneId,selfId,Pos1,Pos2)
	if Pos1 == nil or Pos2 == nil then
		x502024_NotifyTips( sceneId, selfId, "#{SLDZ_100805_107}" )
		return
	end
	if Pos1 == Pos2 then
		x502024_NotifyTips( sceneId, selfId, "放入的装备数据异常！请仔细检查！" )
		return
	end
	if LuaFnIsItemLocked(sceneId, selfId, Pos1) ~= 0 or LuaFnIsItemLocked(sceneId, selfId, Pos2) ~= 0 then
		x502024_NotifyTips( sceneId, selfId,"#{DPMCS_180827_4}") --物品已加锁
		return
	end
	local nEquipID = GetItemTableIndexByIndex(sceneId, selfId, Pos1)
	local nEquipID_2 = GetItemTableIndexByIndex(sceneId, selfId, Pos2)	
	local isLiuboEquip, needMoney,nNextEquip,nNextEquipStar = LuaFnGetLiuboEquipStarUpInfo(nEquipID)
	local oldQual = LuaFnGetItmQual(sceneId,selfId,Pos1)
	local oldQua2 = LuaFnGetItmQual(sceneId,selfId,Pos2)
	local EquipLevel = GetBagItemLevel(sceneId,selfId,Pos1)
	local EquipLeve2 = GetBagItemLevel(sceneId,selfId,Pos2)
	local equip_point = LuaFnGetBagEquipType(sceneId,selfId, Pos1)
	local equip_poin2 = LuaFnGetBagEquipType(sceneId,selfId, Pos2)
	if oldQual >= 8 then
	   x502024_NotifyTips( sceneId, selfId,"#H此六博装备已达八星，不可继续提升或者作为材料装备。 ")
	   return
	end
	if isLiuboEquip ~= nil and isLiuboEquip == 1 and needMoney~=nil then
		-- 六星六博的升级金钱为负数 新增逻辑
		if needMoney <= 0 then
			x502024_NotifyTips( sceneId, selfId,"#H此六博装备已达八星，不可继续提升或者作为材料装备。 ")
			return
		end
		if oldQua2 ~= oldQual then --星级判断
			x502024_NotifyTips( sceneId, selfId,"#{SLDZ_100805_109}")
			return
		end
		if EquipLevel ~= EquipLeve2 then --等级判断
			x502024_NotifyTips( sceneId, selfId,"#{SLDZ_100805_109}")
			return
		end
		if equip_point ~= equip_poin2 then --装备类型判断
			x502024_NotifyTips( sceneId, selfId,"#{SLDZ_100805_109}")
			return
		end
		--辅助装备检测逻辑
		local bSp = 0	
		-- 镶嵌有宝石的不能作为合成材料
		local nGemCount = GetGemEmbededCount(sceneId,selfId,Pos2)
		if nGemCount ~= nil and nGemCount > 0 then
			bSp = 1
		end
		-- 强化等级
		local nCurStrengthLevel = GetBagItemParam(sceneId,selfId,Pos2,3,1)
		if nCurStrengthLevel > 0 then
			bSp = 1
		end
		--看看雕纹
		local nDWLevel_1,nDWLevel_2 = CallScriptFunction(900014, "DWShikeJC", sceneId, selfId,Pos2)
		if nDWLevel_1 ~= 0 or nDWLevel_2 ~= 0 then
			bSp = 1
		end
		if 1 == bSp then
			x502024_NotifyTips( sceneId, selfId,"#{SLDZ_181110_02}")
			return
		end
		--看看钱够不够
		local nMoneyJZ = GetMoneyJZ(sceneId,selfId)
		local nMoneyJB = GetMoney(sceneId,selfId)
		local nMoneySelf = nMoneyJZ + nMoneyJB
		if nMoneySelf < needMoney then
			x502024_NotifyTips( sceneId, selfId,"#{SLDZ_100805_100}" )
			return
		end
		--扣钱升级装备
		LuaFnCostMoneyWithPriority( sceneId, selfId,needMoney) --扣钱
		--扣材料装备
		LuaFnEraseItem(sceneId,selfId,Pos2)
		--完工上电视
		 LuaFnEquipTransToNew(sceneId,selfId,Pos1,nNextEquip)
		 LuaFnSetItemQual(sceneId,selfId,Pos1,oldQual + 1)
		 -- LuaFnRewashEquipAttr(sceneId,selfId,Pos1)--刷新出属性条目
		x502024_NotifyTips( sceneId, selfId,"你的"..GetItemName(sceneId,nEquipID).."提升星级成功！" )
		local nNewItemID = GetItemTableIndexByIndex(sceneId, selfId, Pos1)
		local nMsg = format("#{_INFOUSR%s}#I大喊：“宁失一马，不失一先；宁失一先，不失一星！”话音未落，手中的%s#I星光闪耀，从%s#I星提升到了%s#I星！",
					GetName(sceneId,selfId),
					GetItemName(sceneId,nNextEquip),
					oldQual,
					oldQual + 1)
		BroadMsgByChatPipe(sceneId, selfId, nMsg, 4)
		return
	else
		x502024_NotifyTips( sceneId, selfId,"#{SLDZ_181110_01}")
		return
	end
end
